def system(ref=NO_REF, name=None):
    return SYSTEM.format(name=name or random.choice(NAMES)) + "\n\nСправка Nuvora:\n" + ref


def ref_of(*arts):
    return "\n\n".join(f"### {q}\n{a}" for _, _, q, a in arts)


