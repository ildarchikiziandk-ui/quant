def main():
    rows = []
    for art in ARTICLES:
        _, _, q, a = art
        ql = q[0].lower() + q[1:]
        asks = random.sample(ASK, 5)
        for ask in asks:
            user = ask.format(q=q, ql=ql)
            ans = random.choice(LEAD) + a + random.choice(TAIL)
            other = random.choice([x for x in ARTICLES if x is not art])
            ref = ref_of(art, other) if random.random() < .6 else ref_of(other, art)
            rows.append([{"role": "system", "content": system(ref)}, {"role": "user", "content": user}, {"role": "assistant", "content": ans}])
    for pairs, k in ((ABOUT, 3), (CREATIVE, 2), (SAFE, 2), (UNKNOWN, 2)):
        for q, a in pairs:
            for _ in range(k):
                variant = random.choice([q, q.lower(), q.rstrip("?!.") , q + " пожалуйста"])
                rows.append([{"role": "system", "content": system()}, {"role": "user", "content": variant}, {"role": "assistant", "content": a}])
    # короткие диалоги в два хода: модель учится помнить, о чём шла речь
    for (q1, a1), (q2, a2) in [(("Привет", "Привет! 👋 Я Нува. Чем помочь?"), ("Как получить искры?", ABOUT[19][1])),
                               (("Что такое Nuvora+?", ABOUT[20][1]), ("А сколько стоит?", "33 ₽ за месяц или 99 ₽ за 3 месяца 🙂")),
                               (("Придумай подпись к фото с моря", CREATIVE[0][1]), ("А ещё одну?", "Море шепчет: «Оставайся ещё на денёк» 🌊")),
                               (("Какие есть игры?", ABOUT[24][1]), ("А как позвать друга?", "Открой переписку с другом, нажми «+» слева от поля ввода и выбери игру — карточка появится прямо в чате 🎮"))]:
        rows.append([{"role": "system", "content": system()}, {"role": "user", "content": q1}, {"role": "assistant", "content": a1},
                     {"role": "user", "content": q2}, {"role": "assistant", "content": a2}])
    random.shuffle(rows)
    out = os.path.join(ROOT, "tools", "nuva_train.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps({"messages": r}, ensure_ascii=False) + "\n")
    print(f"{len(rows)} примеров → {out}")


if __name__ == "__main__":
    main()
